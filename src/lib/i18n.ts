export const DICTS: Record<Lang, Dict> = { en, zh };
export type { Dict };

export function useT(): Dict {
  return DICTS[useStore((s) => s.lang)];
}

export const chName = (c: Channel, lang: Lang) => (lang === "zh" ? c.nameZh : c.name);
export const chAltName = (c: Channel, lang: Lang) => (lang === "zh" ? c.name : c.nameZh);
export const chDistrict = (c: Channel, lang: Lang) => (lang === "zh" ? c.districtZh : c.district);
export const chRegion = (c: Channel, lang: Lang) => (lang === "zh" ? c.regionZh : c.region);
export const groupLabel = (g: ChannelGroup, lang: Lang) => (lang === "zh" ? g.labelZh : g.label);
